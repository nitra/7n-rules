/**
 * Спільна стеля розміру wasm-компонента для size-budget гейтів усіх гостей
 * (`wasm-plugin-parity*.test.mjs`).
 *
 * # Звідки взялося 2,5 MiB і чому його підняли
 *
 * Початкове число — не зовнішнє обмеження, а **оцінка** зі спайка
 * `docs/specs/2026-08-01-wasm-ast-strategy.md` (розділ «Рішення», п. 2),
 * порахована під ОДНОГО гостя — AST-концерн-крейт `plugin-lang-js`:
 * «549 KB парсер + запас під wit-bindgen glue, бізнес-логіку пʼяти
 * concern-ів і майбутнє розширення». Далі те саме число механічно
 * скопіювали в гейти решти чотирьох гостей, композиція яких із тим
 * розрахунком не має нічого спільного: `plugin-ci-github` не містить
 * `oxc_parser` узагалі, а `plugin-lang-php` займає 5,6% стелі.
 *
 * Уперся в стелю саме `plugin-ci-github` (2 604 774 Б, 99,4% старої стелі) —
 * гість, для якого 2,5 MiB ніколи не рахували. Піднято спершу до 4 MiB, потім
 * до 10 MiB — щоб розблокувати перенесення в цього гостя родини концернів
 * `template-deep-merge`/`vscode-ext-add` (15 концернів, виміряні ~24 КБ на
 * перший порт у гостя без JSON-інфраструктури; при 4 MiB запасу вистачало,
 * але без комфорту на подальші хвилі).
 *
 * # Що цей гейт ловить, а що ні
 *
 * Ловить: раптовий стрибок розміру від необачно затягнутої залежності —
 * тобто це backstop від втечі, а не робочий бюджет. При 10 MiB найбільший
 * гість займає ~25%, тож жодного реального порту стеля вже не стримує; це
 * СВІДОМО, після того як зʼясувалось, що вона стримувала не зростання, а
 * міграцію.
 * НЕ ловить: повзучий ріст гостя, який має великий запас — `plugin-lang-php`
 * може вирости в 20 разів і лишитись зеленим. Єдина плоска стеля на пʼятьох
 * гостей із розкидом 1,4%…24,8% — слабкий детектор дрейфу; окремі бюджети
 * на гостя записані відкритим питанням у реєстрі (§2.55).
 *
 * # Чим стеля НЕ підпирається
 *
 * Жодного зовнішнього ліміту тут немає: рантайм-обмеження на розмір
 * компонента немає, у CI окремого size-гейта немає (перевірено —
 * `.github/workflows` не міряє wasm), npm-пакет стелею не обмежений.
 * Тому число — інженерна домовленість, а не фізика. Резерв на випадок,
 * якщо запас знову підійде до нуля: `lto = "fat"` (−270 КБ, §2.1 реєстру,
 * свідомо не взятий, бо вимагає `[profile.release]` на весь workspace).
 */

/** Стеля розміру одного wasm-компонента, байти (10 MiB). */
export const WASM_SIZE_BUDGET_BYTES = 10 * 1024 * 1024

/** Людиночитний підпис стелі для назв тестів — щоб не дублювати «MiB» текстом. */
export const WASM_SIZE_BUDGET_LABEL = `${WASM_SIZE_BUDGET_BYTES} Б (${WASM_SIZE_BUDGET_BYTES / 1024 / 1024} MiB)`
