/**
 * Ліміт паралельних воркерів vitest — регресія на МОВЧАЗНИЙ no-op конфігу.
 *
 * Історія: обмежувач додавався як `poolOptions: { forks: { maxForks: 4 } }`,
 * але vitest 4 прибрав `poolOptions` (pool rework) і підняв його поля на
 * верхній рівень. Невідомий ключ не валив конфіг — vitest його просто
 * ІГНОРУВАВ, друкуючи `DEPRECATED` серед іншого виводу. Ліміт був мертвий
 * ~добу: заміряно на цьому ж наборі тестів — пік 12 node-процесів зі старим
 * ключем проти 7 з `maxWorkers` (з явним `--maxWorkers=10` — 11, тобто пул
 * і справді слухається лише нового ключа).
 *
 * Чому тест, а не просто виправлений конфіг: обидві помилки цього класу —
 * перейменування ключа апстрімом і випадкове повернення старої форми при
 * рефакторі — виглядають однаково (конфіг на місці, ефекту нема) і НЕ
 * помітні у зеленому прогоні. Тут вони стають червоними.
 *
 * Тест НЕ перевіряє саме число процесів (це залежить від машини й від того,
 * скільки test-файлів у наборі) — він перевіряє, що ліміт узагалі
 * оголошений у формі, яку поточний vitest читає.
 */
import { describe, expect, test } from 'vitest'

/** Обидва конфіги репозиторію: кореневий і `npm/`-локальний. */
const CONFIGS = [
  ['vitest.config.mjs', await import('../../vitest.config.mjs')],
  ['npm/vitest.config.js', await import('../vitest.config.js')],
]

describe('vitest — ліміт воркерів оголошений у формі, яку читає поточний vitest', () => {
  test.each(CONFIGS)('%s: maxWorkers на верхньому рівні test-секції', (_name, mod) => {
    expect(mod.default.test.maxWorkers).toBe(4)
  })

  test.each(CONFIGS)('%s: знятий poolOptions не повернувся', (_name, mod) => {
    // `poolOptions` тут означав би тихо проігнорований конфіг — саме той стан,
    // який цей файл і ловить.
    expect(mod.default.test).not.toHaveProperty('poolOptions')
  })
})
